  const LANGS = ['tr', 'en'];
  let lang = 'tr';

  function detect(saved) {
    if (LANGS.includes(saved)) return saved;
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    return /^tr\b/i.test(nav) ? 'tr' : 'en';
  }

  function t(key, vars) {
    let s = dict[lang][key];
    if (s == null) s = dict.tr[key];
    if (s == null) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return s;
  }

  /** data-i18n, data-i18n-title, data-i18n-ph özniteliklerini doldurur. */
  function applyStatic(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  }

  function setLang(l) {
    lang = LANGS.includes(l) ? l : 'tr';
    document.documentElement.lang = lang;
    applyStatic();
  }

  window.SeqI18n = { t, setLang, detect, applyStatic, getLang: () => lang, LANGS };
